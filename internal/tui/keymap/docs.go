package keymap

import (
	"fmt"
	"strings"
)

// notAvailable marks actions whose keys are bound but whose feature has not
// shipped yet.
var notAvailable = map[Action]string{}

// Markdown renders the keymaps page of the docs site: one table per help
// group with the keys of the default and the vim keymap. It is generated from
// the same tables as the help overlay, so the two cannot drift.
func Markdown() string {
	def, vim := Default(), Vim()
	var b strings.Builder
	b.WriteString("---\nlayout: ../../layouts/DocsLayout.astro\ntitle: Keymaps\n---\n\n")
	b.WriteString("<!-- Generated by `go test ./internal/tui/keymap -run TestGenerateDocs -update`. Do not edit. -->\n\n")
	b.WriteString("# Keymaps\n\n")
	b.WriteString("The TUI has two keymaps, chosen with `tui.keymap` in the [config file](/docs/configuration/) " +
		"or the `:keymap` command: `default` (arrows and PgUp/PgDn) and `vim` (the same keys plus hjkl and friends). " +
		"Press `F1` or `?` in the TUI to see the keys for the current context. " +
		"For the rest of the TUI, see the [TUI guide](/docs/tui/).\n\n")
	for i, g := range groups {
		fmt.Fprintf(&b, "## %s\n\n| Action | Default | Vim |\n| --- | --- | --- |\n", g.title)
		for _, a := range g.actions {
			desc := descriptions[a]
			if note, ok := notAvailable[a]; ok {
				desc = strings.SplitN(desc, " (", 2)[0] + " (" + note + ")"
			}
			fmt.Fprintf(&b, "| %s | %s | %s |\n", desc, keysCell(def, a), keysCell(vim, a))
		}
		if i < len(groups)-1 {
			b.WriteString("\n")
		}
	}
	return b.String()
}

func keysCell(m Map, a Action) string {
	keys := m.Binding(a).Keys()
	cells := make([]string, len(keys))
	for i, k := range keys {
		cells[i] = "`" + strings.ReplaceAll(k, " ", "") + "`"
	}
	return strings.Join(cells, " ")
}
