// functionsAllowed is functionNames as a set.
var functionsAllowed = func() map[string]bool {
	m := map[string]bool{}
	for _, f := range strings.Fields(functionNames) {
		m[f] = true
	}
	return m
}()

// reservedBeforeParen are reserved words a '(' after which opens a
// subquery, a list or a clause's body (FROM (, IN (, WITHIN GROUP (,
// MATCH (): Vertica's grammar cannot call a function by these
// names. Non-reserved words that sometimes precede '(' are judged in
// context (notACall) or as calls.
var reservedBeforeParen = map[string]bool{
	"SELECT": true, "FROM": true, "JOIN": true, "ON": true, "WHERE": true, "AND": true, "OR": true, "NOT": true,
	"IN": true, "AS": true, "ANY": true, "ALL": true, "SOME": true, "UNION": true, "INTERSECT": true,
	"EXCEPT": true, "MINUS": true, "USING": true, "WITH": true, "HAVING": true, "WHEN": true,
	"THEN": true, "ELSE": true, "CASE": true, "DISTINCT": true, "LIMIT": true,
	"OFFSET": true, "GROUP": true, "MATCH": true, "TO": true,
}

// typeNames are types that take a length, precision or scale in
// parentheses: VARCHAR(20), NUMERIC(10,2), TIMESTAMP(3). They are skipped
// only right after :: or AS (CAST(x AS NUMERIC(10,2))).
var typeNames = map[string]bool{
	"CHAR": true, "CHARACTER": true, "VARCHAR": true, "VARYING": true, "NUMERIC": true, "DECIMAL": true,
	"NUMBER": true, "MONEY": true, "FLOAT": true, "TIMESTAMP": true, "TIMESTAMPTZ": true, "TIME": true,
	"TIMETZ": true, "BINARY": true, "VARBINARY": true, "BYTEA": true, "RAW": true, "INTERVAL": true,
}
