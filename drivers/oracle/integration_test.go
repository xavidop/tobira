// testImage is the Oracle Database Free image the integration suite runs
// against (Oracle AI Database 26ai Free, version 23.26.3, slim flavour).
const testImage = "gvenzl/oracle-free:23.26.3-slim"

// testDSN is the oracle:// URL of the app user (schema TOBIRA) in the
// container's FREEPDB1, shared by every test in the package; adminDSN is
// SYSTEM's.
var testDSN, adminDSN, testHostPort string

func TestMain(m *testing.M) { os.Exit(runMain(m)) }

// leakBaseline is taken after the container and seed connection exist, so
// testcontainers' and the docker client's goroutines are not counted.
var leakBaseline goleak.Option

func runMain(m *testing.M) int {
	ctx := context.Background()
	ctr, err := testcontainers.Run(ctx, testImage,
		testcontainers.WithExposedPorts("1521/tcp"),
		testcontainers.WithEnv(map[string]string{
			"ORACLE_PASSWORD":   "tobira",
			"APP_USER":          "tobira",
			"APP_USER_PASSWORD": "tobira",
		}),
		testcontainers.WithWaitStrategy(wait.ForLog("DATABASE IS READY TO USE!").WithStartupTimeout(10*time.Minute)),
	)
	if err != nil {
		fmt.Fprintln(os.Stderr, "start oracle container:", err)
		if ctr != nil {
			_ = testcontainers.TerminateContainer(ctr)
		}
		return 1
	}
	defer func() { _ = testcontainers.TerminateContainer(ctr) }()
	testHostPort, err = ctr.PortEndpoint(ctx, "1521/tcp", "")
	if err != nil {
		fmt.Fprintln(os.Stderr, "endpoint:", err)
		return 1
	}
	testDSN = "oracle://tobira:tobira@" + testHostPort + "/FREEPDB1"
	adminDSN = "oracle://system:tobira@" + testHostPort + "/FREEPDB1"
	if err := seed(ctx); err != nil {
		fmt.Fprintln(os.Stderr, "seed:", err)
		return 1
	}
	leakBaseline = goleak.IgnoreCurrent()
	code := m.Run()
	if code == 0 {
		if err := goleak.Find(leakBaseline); err != nil {
			fmt.Fprintln(os.Stderr, "goroutine leak:", err)
			return 1
		}
	}
	return code
}

// peopleDDL creates People with quoted lower-case names, so its columns are
// named as drivertest.People names them.
const peopleDDL = `CREATE TABLE "%s" ("id" NUMBER(10) PRIMARY KEY, "name" VARCHAR2(255) NOT NULL,
"email" VARCHAR2(255) NOT NULL UNIQUE, "age" NUMBER(10), "score" NUMBER(10,2), "active" BOOLEAN,
"created_at" TIMESTAMP WITH TIME ZONE, "tags" JSON)`

// seedPeople creates table name in the session's schema and loads People.
func seedPeople(ctx context.Context, db *sql.DB, name string) error {
	if _, err := db.ExecContext(ctx, fmt.Sprintf(peopleDDL, name)); err != nil {
		return err
	}
	ins := fmt.Sprintf(`INSERT INTO "%s" ("id", "name", "email", "age", "score", "active", "created_at", "tags") VALUES (:1, :2, :3, :4, :5, :6, :7, :8)`, name)
	for _, r := range drivertest.People.Rows {
		args := make([]any, len(r))
		for i, v := range r {
			a, err := toArg(v)
			if err != nil {
				return err
			}
			args[i] = a
		}
		if _, err := db.ExecContext(ctx, ins, args...); err != nil {
			return fmt.Errorf("insert %v: %w", r[0], err)
		}
	}
	return nil
}

func seed(ctx context.Context) error {
	db, err := sql.Open("oracle", testDSN)
	if err != nil {
		return err
	}
	defer func() { _ = db.Close() }()
	if err := seedPeople(ctx, db, "tobira_people"); err != nil {
		return err
	}
	for _, s := range []string{
		`CREATE VIEW "tobira_people_view" AS SELECT "id", "name" FROM "tobira_people"`,
		`CREATE TABLE tobira_orders (id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, person_id NUMBER(10) NOT NULL,
		  total NUMBER(8,2) DEFAULT 0, doubled NUMBER(9,2) GENERATED ALWAYS AS (total * 2) VIRTUAL,
		  note VARCHAR2(50 CHAR) DEFAULT 'n/a', created DATE DEFAULT SYSDATE,
		  CONSTRAINT fk_orders_person FOREIGN KEY (person_id) REFERENCES "tobira_people"("id"))`,
		`CREATE INDEX tobira_orders_person_total ON tobira_orders (person_id, total)`,
		`CREATE UNIQUE INDEX tobira_orders_note ON tobira_orders (note)`,
		`COMMENT ON TABLE tobira_orders IS 'orders table'`,
		`COMMENT ON COLUMN tobira_orders.note IS 'free text'`,
		`CREATE TABLE tobira_big (n NUMBER(10) PRIMARY KEY)`,
		`INSERT INTO tobira_big SELECT LEVEL FROM dual CONNECT BY LEVEL <= 1000`,
		`CREATE SEQUENCE tobira_seq`,
		`BEGIN DBMS_STATS.GATHER_TABLE_STATS(USER, '"tobira_people"'); END;`,
	} {
		if _, err := db.ExecContext(ctx, s); err != nil {
			return fmt.Errorf("%.60s: %w", s, err)
		}
	}
	adm, err := sql.Open("oracle", adminDSN)
	if err != nil {
		return err
	}
	defer func() { _ = adm.Close() }()
	for _, s := range []string{
		`CREATE USER tobira_ns IDENTIFIED BY tobira QUOTA UNLIMITED ON users`,
		`CREATE TABLE tobira_ns.things (id NUMBER(10) PRIMARY KEY, label VARCHAR2(20))`,
		`INSERT INTO tobira_ns.things VALUES (1, 'in-ns')`,
		`GRANT SELECT, INSERT, UPDATE, DELETE ON tobira_ns.things TO tobira`,
		`CREATE USER "tobira_lower" IDENTIFIED BY tobira QUOTA UNLIMITED ON users`,
		`CREATE TABLE "tobira_lower"."Mixed" ("Id" NUMBER(10) PRIMARY KEY)`,
		`GRANT SELECT ON "tobira_lower"."Mixed" TO tobira`,
	} {
		if _, err := adm.ExecContext(ctx, s); err != nil {
			return fmt.Errorf("%.60s: %w", s, err)
		}
	}
	for _, tbl := range []string{`"tobira_people"`, "tobira_orders", "tobira_big", "tobira_ns.things"} {
		if err := settleDB(ctx, db, tbl); err != nil {
			return fmt.Errorf("settle %s: %w", tbl, err)
		}
	}
	return nil
}

// admin opens a plain database/sql handle on the app schema, outside the
// driver under test.
func admin(t *testing.T) *sql.DB {
	t.Helper()
	db, err := sql.Open("oracle", testDSN)
	if err != nil {
		t.Fatal(err)
	}
	t.Cleanup(func() { _ = db.Close() })
	return db
}

// openOra opens a connection to the shared container and checks on cleanup
// that every pooled session is back.
func openOra(t *testing.T, readOnly bool) *conn {
	t.Helper()
	c, err := New().Open(context.Background(), driver.ConnConfig{DSN: testDSN, ReadOnly: readOnly})
	if err != nil {
		t.Fatal(err)
	}
	oc := c.(*conn)
	t.Cleanup(func() {
		requireIdle(t, oc)
		_ = c.Close()
	})
	return oc
}

// requireIdle fails unless no pooled session is still in use.
func requireIdle(t *testing.T, c *conn) {
	t.Helper()
	deadline := time.Now().Add(3 * time.Second)
	for c.db.Stats().InUse != 0 {
		if time.Now().After(deadline) {
			t.Errorf("%d sessions still in use", c.db.Stats().InUse)
			return
		}
		time.Sleep(10 * time.Millisecond)
	}
}

var scratchSeq atomic.Int64

// scratch copies People into a private table, so tests can write.
func scratch(t *testing.T, db *sql.DB) string {
	t.Helper()
	name := fmt.Sprintf("tobira_scratch_%d", scratchSeq.Add(1))
	if err := seedPeople(context.Background(), db, name); err != nil {
		t.Fatal(err)
	}
	t.Cleanup(func() { mustExec(t, db, `DROP TABLE "`+name+`" PURGE`) })
	settle(t, db, `"`+name+`"`)
	return name
}

// settle waits until a read-only transaction can read table: Oracle refuses
// (ORA-01466) to read a table created within the last few seconds of a
// read-only transaction's snapshot.
func settle(t *testing.T, db *sql.DB, table string) {
	t.Helper()
	if err := settleDB(context.Background(), db, table); err != nil {
		t.Fatalf("settle %s: %v", table, err)
	}
}

func settleDB(ctx context.Context, db *sql.DB, table string) error {
	deadline := time.Now().Add(20 * time.Second)
	for {
		tx, err := db.BeginTx(ctx, nil)
		if err != nil {
			return err
		}
		_, err = tx.ExecContext(ctx, "SET TRANSACTION READ ONLY")
		if err == nil {
			var n int64
			err = tx.QueryRowContext(ctx, "SELECT COUNT(*) FROM "+table).Scan(&n)
		}
		_ = tx.Rollback()
		if err == nil || !strings.Contains(err.Error(), "ORA-01466") || time.Now().After(deadline) {
			return err
		}
		time.Sleep(250 * time.Millisecond)
	}
}

func ctxT(t *testing.T) context.Context {
	t.Helper()
	ctx, cancel := context.WithTimeout(context.Background(), 60*time.Second)
	t.Cleanup(cancel)
	return ctx
}

func contextWithCancel(t *testing.T) (context.Context, context.CancelFunc) {
	t.Helper()
	ctx, cancel := context.WithTimeout(context.Background(), 60*time.Second)
	t.Cleanup(cancel)
	return ctx, cancel
}

func mustExec(t *testing.T, db *sql.DB, stmt string, args ...any) {
	t.Helper()
	if _, err := db.ExecContext(context.Background(), stmt, args...); err != nil {
		t.Fatalf("%s: %v", stmt, err)
	}
}

func collect(t *testing.T, c driver.Querier, q driver.Query) ([]driver.Row, driver.Stats, []driver.Column) {
	t.Helper()
	rs, err := c.Query(ctxT(t), q)
	if err != nil {
		t.Fatalf("Query(%q): %v", q.Text, err)
	}
	cols := rs.Columns()
	rows, st, err := driver.Collect(ctxT(t), rs, 0)
	if err != nil {
		t.Fatalf("Collect(%q): %v", q.Text, err)
	}
	return rows, st, cols
}

func queryErr(t *testing.T, c driver.Querier, q driver.Query) error {
	t.Helper()
	rs, err := c.Query(ctxT(t), q)
	if err != nil {
		return err
	}
	_, _, err = driver.Collect(ctxT(t), rs, 0)
	return err
}

// count returns SELECT COUNT(*) of a query fragment, read outside the driver.
func count(t *testing.T, db *sql.DB, from string) int64 {
	t.Helper()
	var n int64
	if err := db.QueryRow("SELECT COUNT(*) FROM " + from).Scan(&n); err != nil {
		t.Fatalf("count %s: %v", from, err)
	}
	return n
}

// tableExists reports whether the app schema has a table of that name.
func tableExists(t *testing.T, db *sql.DB, name string) bool {
	t.Helper()
	var n int64
	if err := db.QueryRow("SELECT COUNT(*) FROM user_tables WHERE table_name = :1", name).Scan(&n); err != nil {
		t.Fatal(err)
	}
	return n > 0
}

// currentSchema reads CURRENT_SCHEMA through the driver.
func currentSchema(t *testing.T, c driver.Querier) string {
	t.Helper()
	rows, _, _ := collect(t, c, driver.Query{Text: "SELECT SYS_CONTEXT('USERENV', 'CURRENT_SCHEMA') FROM dual"})
	return rows[0][0].String()
}

func names(cols []driver.Column) string {
	out := make([]string, len(cols))
	for i, c := range cols {
		out[i] = c.Name
	}
	return strings.Join(out, ",")
}
